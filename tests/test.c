#include <stdio.h>

unsigned long long flip(unsigned long long number) {
    unsigned long long output = 0;
    for (int i = 1; i <= 8; i++) {
        output <<= 8;
        output += number & 0b11111111;
        number >>= 8;
    }
    return output;
}


